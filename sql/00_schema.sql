-- 00_schema.sql — tables of the commodities database (DuckDB).
--
-- One table per grain. Primary keys state the grain and make every load
-- idempotent (INSERT ... ON CONFLICT DO UPDATE). Referential integrity
-- (every code exists in dim_commodity) is checked by tests/test_sql.py rather
-- than by FOREIGN KEY clauses, which DuckDB does not allow on upserted tables.

-- One row per commodity: static contract specifications.
CREATE TABLE IF NOT EXISTS dim_commodity (
    code                VARCHAR PRIMARY KEY,
    name                VARCHAR NOT NULL,
    unit                VARCHAR NOT NULL,          -- price unit, e.g. USD/bbl
    currency            VARCHAR NOT NULL,
    point_value         DOUBLE  NOT NULL CHECK (point_value > 0),  -- contract size
    point_unit          VARCHAR NOT NULL,
    usd_per_bbl_factor  DOUBLE,                    -- 42 for USD/gal products, NULL for gas
    expiry_rule         VARCHAR NOT NULL
);

-- One row per NYMEX business day (generated by energycurves.data.calendar).
CREATE TABLE IF NOT EXISTS dim_business_day (
    date DATE PRIMARY KEY
);

-- One row per listed contract: delivery month and last trading day.
CREATE TABLE IF NOT EXISTS dim_contract_calendar (
    code             VARCHAR NOT NULL,
    delivery_month   DATE    NOT NULL CHECK (day(delivery_month) = 1),
    last_trade_date  DATE    NOT NULL CHECK (last_trade_date < delivery_month),
    PRIMARY KEY (code, delivery_month)
);

-- One settlement per date and contract slot, as published by the EIA (raw).
CREATE TABLE IF NOT EXISTS fact_price_daily (
    date      DATE     NOT NULL,
    code      VARCHAR  NOT NULL,
    contract  TINYINT  NOT NULL CHECK (contract BETWEEN 1 AND 4),
    settle    DOUBLE   NOT NULL,                   -- may be negative (CL, 2020-04-20)
    volume    DOUBLE,                              -- not published by the EIA
    source    VARCHAR  NOT NULL,
    PRIMARY KEY (date, code, contract)
);

-- One clean curve point per trade date and slot, with its delivery month.
-- Derived from fact_price_daily by 15_build_curve.sql.
CREATE TABLE IF NOT EXISTS fact_curve (
    trade_date       DATE     NOT NULL,
    code             VARCHAR  NOT NULL,
    contract         TINYINT  NOT NULL CHECK (contract BETWEEN 1 AND 4),
    delivery_month   DATE     NOT NULL,
    last_trade_date  DATE     NOT NULL CHECK (last_trade_date >= trade_date),
    tau              DOUBLE   NOT NULL CHECK (tau >= 0),   -- years to expiry, Act/365
    settle           DOUBLE   NOT NULL,
    source           VARCHAR  NOT NULL,
    PRIMARY KEY (trade_date, code, contract)
);

-- One close per snapshot date and delivery month (full live strip).
CREATE TABLE IF NOT EXISTS fact_curve_snapshot (
    snapshot_date   DATE     NOT NULL,
    code            VARCHAR  NOT NULL,
    delivery_month  DATE     NOT NULL CHECK (day(delivery_month) = 1),
    ticker          VARCHAR  NOT NULL,
    settle          DOUBLE   NOT NULL CHECK (settle > 0),
    volume          DOUBLE,
    source          VARCHAR  NOT NULL,
    PRIMARY KEY (snapshot_date, code, delivery_month)
);

-- One spot price per date and series.
CREATE TABLE IF NOT EXISTS fact_spot_daily (
    date       DATE     NOT NULL,
    series_id  VARCHAR  NOT NULL,
    code       VARCHAR,                            -- related futures, if any
    price      DOUBLE   NOT NULL,
    unit       VARCHAR  NOT NULL,
    source     VARCHAR  NOT NULL,
    PRIMARY KEY (date, series_id)
);

-- One stock level per week and region.
CREATE TABLE IF NOT EXISTS fact_inventory (
    week_ending  DATE     NOT NULL,
    code         VARCHAR  NOT NULL,
    region       VARCHAR  NOT NULL,
    stock        DOUBLE   NOT NULL CHECK (stock >= 0),
    unit         VARCHAR  NOT NULL,
    source       VARCHAR  NOT NULL,
    PRIMARY KEY (week_ending, code, region)
);

-- One interest rate fixing per date and series (percent).
CREATE TABLE IF NOT EXISTS fact_rate_daily (
    date       DATE     NOT NULL,
    series_id  VARCHAR  NOT NULL,
    value      DOUBLE   NOT NULL,
    unit       VARCHAR  NOT NULL,
    source     VARCHAR  NOT NULL,
    PRIMARY KEY (date, series_id)
);

-- One FX fixing per date and pair (EURUSD = USD per 1 EUR).
CREATE TABLE IF NOT EXISTS fx_rates (
    date    DATE     NOT NULL,
    pair    VARCHAR  NOT NULL,
    rate    DOUBLE   NOT NULL CHECK (rate > 0),
    source  VARCHAR  NOT NULL,
    PRIMARY KEY (date, pair)
);
